/** Значение реквизита либо заметная метка, если он не заполнен. */
export function req(value: string): string {
  return value && value.trim() ? value : "— не указано —";
}

/** Список незаполненных обязательных реквизитов. */
export function missingLegalFields(): string[] {
  const out: string[] = [];
  const need: [string, string][] = [
    ["Полное наименование", LEGAL.fullName],
    ["ИНН", LEGAL.inn],
    ["ОГРН", LEGAL.ogrn],
    ["Юридический адрес", LEGAL.legalAddress],
    ["Почтовый адрес", LEGAL.postAddress],
    ["Руководитель", LEGAL.director],
    ["СРО — наименование", LEGAL.sro.name],
    ["СРО — номер", LEGAL.sro.number],
    ["Ответственный за обработку ПД", LEGAL.pdResponsible],
  ];
  for (const [label, v] of need) if (!v || !v.trim()) out.push(label);
  return out;
}

